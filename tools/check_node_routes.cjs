'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 const dir=path.join(__dirname,'../web/node-studio/core');
 const graph='data:text/javascript;base64,'+Buffer.from(fs.readFileSync(path.join(dir,'graph.js'),'utf8')).toString('base64');
 const m=await import('data:text/javascript;base64,'+Buffer.from(fs.readFileSync(path.join(dir,'model.js'),'utf8').replaceAll('./graph.js',graph)).toString('base64'));
 const types=['garment_input','image_reference','quick_create','image_generate','precision_edit','production_guide','branch_create','branch_merge','blend_create','agent_execute'];
 const catalog=types.map(type=>({type,label:type,placement:['image_reference','agent_execute'].includes(type)?'both':'main',slot:type==='image_reference'?'top':'bottom'}));
 const input=m.makeNode('garment_input',catalog,{front:{url:'/data/main.png'}});
 let w={schemaVersion:1,nodes:[input],order:[input.id],stash:[]};const checks=[];
 const standard=m.makeStandardWorkflow(w,catalog);
 assert.deepEqual(standard.order.map(id=>m.findNode(standard,id).type),['garment_input','quick_create','image_generate','precision_edit','production_guide']);
 assert(standard.nodes.slice(1).every(node=>node.output===null));assert.deepEqual(m.makeStandardWorkflow(standard,catalog),standard);assert.equal(w.nodes.length,1);
 checks.push('new projects get an idempotent real-operation template without fabricated outputs');
 w=m.insertNode(w,'precision_edit',catalog,{afterId:input.id});const edit=w.selectedNodeId;
 w=m.commitNode(w,edit,{imageUrl:'/data/edit.png',projectId:'project-a'});
 w=m.insertNode(w,'agent_execute',catalog,{hostId:edit,slot:'bottom'});const assistant=w.selectedNodeId;
 const old=m.copy(w),output=m.copy(m.findNode(w,edit).output);
 w=m.placeNodeOnCanvas(w,edit,{x:720,y:-80});const detachedRoute=w.selectedLaneId;
 assert.deepEqual(w.order,[input.id]);assert.deepEqual(m.findNode(w,edit).output,output);assert(m.findNode(w,edit).attachments.bottom.includes(assistant));
 assert.deepEqual(m.laneForNode(w,edit).order,[edit]);assert.equal(m.findNode(w,edit).status,'stale');assert.equal(m.upstreamOutput(w,edit).imageUrl,'/data/edit.png');
 assert.deepEqual(old.order,[input.id,edit]);
 checks.push('detach preserves an adopted output and side assistants on a positioned independent route');
 const moved=m.positionRoute(w,detachedRoute,{x:901,y:142});
 assert.equal(m.laneForNode(moved,edit).x,901);assert.equal(m.findNode(moved,edit).status,m.findNode(w,edit).status);
 w=m.insertNode(moved,'precision_edit',catalog,{laneId:detachedRoute,afterId:edit});const downstream=w.selectedNodeId;
 assert.equal(m.upstreamOutput(w,downstream).imageUrl,'/data/edit.png');
 checks.push('independent output routes extend locally and coordinate changes do not change results');
 w=m.insertNodeOnCanvas(w,'image_reference',catalog,{x:60,y:900});const ref=w.selectedNodeId,refRoute=w.selectedLaneId;
 w=m.patchNode(w,ref,{references:[{url:'/data/reference-a.png'},{url:'/data/reference-b.png'}],activeReferenceIndex:1});
 w=m.insertNode(w,'precision_edit',catalog,{laneId:refRoute,afterId:ref});const referenceEdit=w.selectedNodeId;
 assert.equal(m.upstreamOutput(w,referenceEdit).imageUrl,'/data/reference-b.png');assert.equal(m.upstreamOutput(w,referenceEdit).sourceRole,'reference');
 w=m.patchNode(w,ref,{references:[],activeReferenceIndex:0});assert.equal(m.upstreamOutput(w,referenceEdit),null);
 checks.push('reference roots choose an explicit active image and do not fall back when cleared');
 w=m.insertNodeOnCanvas(w,'quick_create',catalog,{x:12,y:1400});assert.equal(m.upstreamOutput(w,w.selectedNodeId),null);
 const emptyTask=w.selectedNodeId;
 w=m.insertNodeOnCanvas(w,'garment_input',catalog,{x:20,y:1600});const second=w.selectedNodeId,secondRoute=w.selectedLaneId;
 w=m.patchNode(w,second,{front:{url:'/data/other-garment.png'}});
 w=m.insertNode(w,'precision_edit',catalog,{laneId:secondRoute,afterId:second});
 assert.equal(m.upstreamOutput(w,w.selectedNodeId).imageUrl,'/data/other-garment.png');
 const otherEdit=w.selectedNodeId;
 w=m.commitNode(w,second,{imageUrl:'/data/edited-root.png',originalImageUrl:'/data/other-garment.png'});
 assert.equal(m.upstreamOutput(w,otherEdit).imageUrl,'/data/edited-root.png');
 w=m.patchNode(w,second,{front:{url:'/data/replacement.png'}});
 assert.equal(m.upstreamOutput(w,otherEdit).imageUrl,'/data/replacement.png');
 checks.push('multiple genuine garment roots and empty draft cards remain independent');
 w=m.moveNodeToGap(w,edit,1,catalog);
 assert.deepEqual(m.findNode(w,edit).output,output);assert.equal(m.laneForNode(w,edit).id,'main');
 assert.deepEqual(m.laneForNode(w,downstream).order,[downstream]);assert.equal(m.upstreamOutput(w,downstream),null);
 assert.equal(m.upstreamOutput(w,emptyTask),null);
 checks.push('reconnecting a saved card retains its pixels and does not lend a foreign source to its old route');
 const duplicate=m.copy(w);duplicate.routes[0].order.push(edit);assert.throws(()=>m.assertWorkflow(duplicate));
 const cross=m.copy(w);m.findNode(cross,emptyTask).params.sourceNodeId=input.id;assert.throws(()=>m.assertWorkflow(cross));
 const nan=m.copy(w);nan.routes[0].x=NaN;assert.throws(()=>m.assertWorkflow(nan));
 const badId=m.copy(w);badId.routes[0].id='../escape';assert.throws(()=>m.assertWorkflow(badId));
 checks.push('duplicate ownership, unscoped sources, nonfinite coordinates and invalid route IDs are rejected');
 m.assertWorkflow(w);assert.deepEqual(JSON.parse(JSON.stringify(w)).routes,w.routes);
 console.log(JSON.stringify({passed:checks.length,checks,externalCalls:0},null,2));
})().catch(error=>{console.error(error);process.exit(1)});
