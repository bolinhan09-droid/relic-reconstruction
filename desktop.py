"""Native Windows shell; owns only its own loopback backend and workspace."""
from __future__ import annotations

import argparse
import base64
import binascii
import ctypes
import json
import os
import socket
import subprocess
import sys
import time
import uuid
import urllib.request
from pathlib import Path

APP_NAME = '遗迹重构'
PORT = 17870
FROZEN = bool(getattr(sys, 'frozen', False))
BASE = Path(sys.executable).resolve().parent if FROZEN else Path(__file__).resolve().parent


def message(text, error=False):
    if os.name == 'nt':
        ctypes.windll.user32.MessageBoxW(None, text, APP_NAME, 0x10 if error else 0x40)
    else:
        print(text, file=sys.stderr)


def read_health(port):
    try:
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        with opener.open(f'http://127.0.0.1:{port}/api/health', timeout=1) as response:
            return json.load(response)
    except Exception:
        return None


class DesktopBridge:
    def __init__(self, workspace):
        self._workspace = workspace
        self._window = None

    def choose_model_directory(self):
        import webview
        result = self._dialog(webview.FileDialog.FOLDER, directory=str(self._workspace))
        return str(result[0]) if result else None

    def _dialog(self, kind, **options):
        # Windows common dialogs need the UI's STA thread, including when a
        # JavaScript bridge call arrives on a Python worker thread.
        native = self._window.native
        if os.name == 'nt' and native.InvokeRequired:
            from System import Func, Object
            return native.Invoke(Func[Object](lambda: self._window.create_file_dialog(kind, **options)))
        return self._window.create_file_dialog(kind, **options)

    def open_workspace(self):
        if os.name == 'nt':
            os.startfile(str(self._workspace))
            return True
        return False

    def save_export(self, name, encoded):
        """Save only explicit generated bytes to the path selected in a native dialog."""
        import webview
        if not isinstance(name, str) or len(name) > 200 or Path(name).name != name or any(char in name for char in '/\\:'):
            return {'ok': False, 'message': '导出文件名无效。'}
        if Path(name).suffix.lower() not in {'.png', '.jpg', '.jpeg', '.webp', '.json', '.zip', '.html', '.svg', '.dxf', '.txt', '.pdf'}:
            return {'ok': False, 'message': '不支持此导出格式。'}
        if not isinstance(encoded, str) or len(encoded) > 90 * 1024 * 1024:
            return {'ok': False, 'message': '导出文件太大，请减小图片后重试。'}
        try:
            content = base64.b64decode(encoded, validate=True)
        except (ValueError, binascii.Error):
            return {'ok': False, 'message': '导出内容无法读取。'}
        exports = self._workspace / 'exports'
        exports.mkdir(exist_ok=True)
        choice = self._dialog(webview.FileDialog.SAVE, directory=str(exports), save_filename=name)
        if not choice:
            return {'ok': False, 'cancelled': True}
        path = Path(choice if isinstance(choice, str) else choice[0])
        temporary = path.with_name(path.name + '.' + uuid.uuid4().hex + '.tmp')
        try:
            temporary.write_bytes(content)
            os.replace(temporary, path)
            return {'ok': True, 'name': path.name}
        except OSError:
            return {'ok': False, 'message': '文件未保存，请检查所选位置是否可写。'}
        finally:
            if temporary.exists():
                temporary.unlink(missing_ok=True)


def serve(port, workspace):
    # Parent sets the path before any backend module is imported.
    os.environ['RELIC_DATA_DIR'] = str(workspace)
    import uvicorn
    from app import app
    uvicorn.run(app, host='127.0.0.1', port=port, log_level='warning',
                access_log=False, loop='asyncio', http='h11', ws='none', log_config=None)


def main():
    parser = argparse.ArgumentParser(description='遗迹重构桌面版')
    parser.add_argument('--data-dir', type=Path)
    parser.add_argument('--port', type=int, default=PORT)
    parser.add_argument('--serve', action='store_true', help=argparse.SUPPRESS)
    parser.add_argument('--smoke-report', type=Path, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if not 1024 <= args.port <= 65535:
        raise ValueError('端口应在 1024–65535 之间。')
    workspace = (args.data_dir or Path(os.environ.get('RELIC_DATA_DIR', str(BASE / 'workspace')))).resolve()
    workspace.mkdir(parents=True, exist_ok=True)
    runtime = workspace / 'runtime'
    runtime.mkdir(exist_ok=True)
    os.environ['RELIC_DATA_DIR'] = str(workspace)
    if args.serve:
        serve(args.port, workspace)
        return

    # Stable port preserves the browser origin and its local drafts. Never kill a
    # competing process or silently move a user into an empty draft origin.
    lockfile = (runtime / 'desktop.lock').open('a+b')
    if os.name == 'nt':
        import msvcrt
        try:
            lockfile.seek(0)
            msvcrt.locking(lockfile.fileno(), msvcrt.LK_NBLCK, 1)
        except OSError:
            handle = ctypes.windll.user32.FindWindowW(None, APP_NAME)
            if handle:
                ctypes.windll.user32.ShowWindow(handle, 9)
                ctypes.windll.user32.SetForegroundWindow(handle)
            else:
                message('这个工作区已经打开，请查看任务栏中的遗迹重构。')
            lockfile.close()
            return
    child = None
    try:
        with socket.socket() as probe:
            try:
                probe.bind(('127.0.0.1', args.port))
            except OSError as exc:
                raise RuntimeError(f'本机端口 {args.port} 正在使用。请关闭之前的桌面窗口后再打开；不会自动停止其他软件。') from exc
        command = [sys.executable]
        if not FROZEN:
            command.append(str(Path(__file__).resolve()))
        command += ['--serve', '--port', str(args.port), '--data-dir', str(workspace)]
        with (runtime / 'desktop-server.log').open('ab', buffering=0) as log:
            child = subprocess.Popen(command, cwd=BASE, stdin=subprocess.DEVNULL,
                                     stdout=log, stderr=log, close_fds=True,
                                     creationflags=subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0)
        deadline = time.monotonic() + 35
        while time.monotonic() < deadline:
            health = read_health(args.port)
            if health and health.get('application') == 'relic-reconstruction':
                break
            if child.poll() is not None:
                raise RuntimeError('本机服务未能启动。详细记录在工作区 runtime/desktop-server.log。')
            time.sleep(.2)
        else:
            raise RuntimeError('启动超时。详细记录在工作区 runtime/desktop-server.log。')

        import webview
        webview.settings['ALLOW_DOWNLOADS'] = True
        webview.settings['OPEN_EXTERNAL_LINKS_IN_BROWSER'] = True
        bridge = DesktopBridge(workspace)
        window = webview.create_window(APP_NAME, f'http://127.0.0.1:{args.port}/',
                                       js_api=bridge, width=1440, height=940,
                                       min_size=(1024, 700), background_color='#e9edeb',
                                       hidden=bool(args.smoke_report),
                                       confirm_close=not bool(args.smoke_report))
        bridge._window = window

        def smoke():
            # Test the actual native WebView2 document, not a substitute browser.
            report = {'nativeWindow': True, 'frozen': FROZEN, 'health': health,
                      'dataDir': str(workspace), 'passed': False}
            try:
                for _ in range(150):
                    try:
                        ready = window.evaluate_js("!!window.RelicNodeStudio && window.RelicNodeStudio.getCatalog().length >= 20")
                        if ready:
                            break
                    except Exception:
                        pass
                    time.sleep(.2)
                report['document'] = window.evaluate_js("JSON.stringify({title:document.title,ready:!!window.RelicNodeStudio&&window.RelicNodeStudio.getCatalog().length>=20,entry:!!document.querySelector('#frontFile'),library:!!document.querySelector('#nodeLibrary'),priorPersist:localStorage.getItem('desktop-smoke-persist')})")
                document = json.loads(report['document'])
                window.evaluate_js("localStorage.setItem('desktop-smoke-persist','kept'); document.querySelector('#sampleButton').click();")
                for _ in range(80):
                    if window.evaluate_js("!document.querySelector('#startButton').disabled"):
                        break
                    time.sleep(.1)
                window.evaluate_js("document.querySelector('#startButton').click();")
                for _ in range(80):
                    if window.evaluate_js("!!window.RelicNodeStudio.getWorkflow()"):
                        break
                    time.sleep(.1)
                report['workflow'] = window.evaluate_js("JSON.stringify(window.RelicNodeStudio.getWorkflow())")
                workflow = json.loads(report['workflow'])
                report['passed'] = bool(document['ready'] and document['entry'] and document['library']
                    and workflow and len(workflow.get('order', [])) == 1
                    and any(node.get('type') == 'garment_input' for node in workflow.get('nodes', [])))
            except Exception as exc:
                report['error'] = type(exc).__name__ + ': ' + str(exc)[:500]
            finally:
                args.smoke_report.parent.mkdir(parents=True, exist_ok=True)
                args.smoke_report.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
                window.destroy()

        webview.start(smoke if args.smoke_report else None, gui='edgechromium',
                      private_mode=False, storage_path=str(workspace / 'window-profile'),
                      localization={'global.quitConfirmation': '关闭会结束本次 AI 任务。请先保存方案，确认关闭？',
                                    'global.ok': '确定', 'global.cancel': '取消'})
    finally:
        if child and child.poll() is None:
            child.terminate()
            try:
                child.wait(timeout=8)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait(timeout=3)
        lockfile.close()


if __name__ == '__main__':
    try:
        main()
    except Exception as exc:
        # No credentials are included in launcher error messages.
        if '--serve' in sys.argv:
            raise
        if '--smoke-report' not in sys.argv:
            message('无法打开遗迹重构。\n\n' + str(exc) + '\n\nWindows 需要 Microsoft Edge WebView2 运行时。', True)
        raise
